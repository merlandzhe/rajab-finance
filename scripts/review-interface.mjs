import { chromium } from 'playwright';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1});
const base='http://127.0.0.1:3000';
const r=await context.request.post(base+'/api/auth',{headers:{origin:base},data:{action:'demo',role:'platform'}});
if(!r.ok())throw Error('Local sign-in '+r.status());
const page=await context.newPage();
await page.route('**/api/platform/access',route=>route.fulfill({json:{requests:[{id:'test',shop_name:'Магазин техники',name:'Тестовый предприниматель',city:'Москва',phone:'+79990000000',status:'new',username:null,telegram_id:1}],companies:[{id:'11111111-1111-4111-8111-111111111111',name:'Раджап',status:'active',expires_at:'2026-12-01T00:00:00Z',linked:true,archived:false}],codes:[],delivery:{pending:0,failed:0}}}));
await page.goto(base+'/crm/platform');
await page.getByText('Управление компанией',{exact:true}).waitFor();
if(await page.getByText('Одобрить и выдать код',{exact:true}).count())throw Error('Request actions leaked into companies');
await page.screenshot({path:'/workspace/scratch/15649ecaf4b9/company-ui.png'});
await page.getByText('Управление компанией',{exact:true}).click();
await page.getByRole('button',{name:'Удалить',exact:true}).click();
await page.getByRole('dialog').waitFor();
await page.screenshot({path:'/workspace/scratch/15649ecaf4b9/delete-ui.png'});
await page.getByRole('button',{name:'Отмена',exact:true}).click();
await page.goto(base+'/crm/platform-requests');
await page.getByText('Рассмотреть заявку',{exact:true}).waitFor();
await page.screenshot({path:'/workspace/scratch/15649ecaf4b9/request-ui.png'});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Horizontal overflow');
await context.request.post(base+'/api/auth',{headers:{origin:base},data:{action:'demo',role:'client'}});
await page.goto(base+'/cabinet?view=profile');
await page.getByText('Изменить профиль',{exact:false}).waitFor();
if(await page.getByText('Уведомления в Telegram',{exact:true}).count())throw Error('Notifications still in profile');
await page.screenshot({path:'/workspace/scratch/15649ecaf4b9/profile-ui.png'});
await page.getByRole('button',{name:'Уведомления',exact:true}).click();
await page.getByText('Уведомления в Telegram',{exact:true}).waitFor();
console.log('Mobile navigation, separate sections, dialog cancellation and buyer notifications passed');
await browser.close();
